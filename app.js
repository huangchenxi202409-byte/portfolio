let currentLanguage = "en";
const buildTypingName = () => {
document.querySelectorAll(".typing-name .word").forEach((word) => {
const text = word.dataset.word || "";
word.textContent = "";
[...text].forEach((char, index) => {
const letter = document.createElement("span");
letter.className = "letter";
letter.textContent = char;
letter.style.animationDelay = `${index * 70 + (word.classList.contains("gradient-word") ? 420 : 0)}ms`;
word.appendChild(letter);
});
});
};
const setActiveView = (view) => {
document.querySelectorAll("[data-view-panel]").forEach((panel) => {
panel.classList.toggle("is-active", panel.dataset.viewPanel === view);
});
document.querySelectorAll("[data-view]").forEach((control) => {
control.classList.toggle("is-active", control.dataset.view === view);
});
};
const applyLanguage = (language) => {
currentLanguage = language;
document.documentElement.lang = language === "en" ? "en" : "zh-CN";
document.querySelectorAll("[data-i18n]").forEach((element) => {
const key = element.dataset.i18n;
element.textContent = translations[language][key];
});
};
document.querySelectorAll("[data-view]").forEach((control) => {
control.addEventListener("click", () => setActiveView(control.dataset.view));
});
document.querySelector(".lang-toggle").addEventListener("click", () => {
applyLanguage(currentLanguage === "en" ? "zh" : "en");
});
const cursorGlow = document.querySelector(".cursor-glow");
const meteorLayer = document.querySelector(".meteor-layer");
let meteorFrame = 0;
window.addEventListener("pointermove", (event) => {
cursorGlow.style.opacity = "1";
cursorGlow.style.left = `${event.clientX}px`;
cursorGlow.style.top = `${event.clientY}px`;
meteorFrame += 1;
if (meteorFrame % 5 !== 0) return;
const meteor = document.createElement("span");
meteor.className = "meteor";
meteor.style.left = `${event.clientX - 34}px`;
meteor.style.top = `${event.clientY - 4}px`;
meteor.style.animation = "meteorFade 620ms ease-out forwards";
meteorLayer.appendChild(meteor);
meteor.addEventListener("animationend", () => meteor.remove(), { once: true });
});
window.addEventListener("pointerleave", () => {
cursorGlow.style.opacity = "0";
});
buildTypingName();
applyLanguage(currentLanguage);
